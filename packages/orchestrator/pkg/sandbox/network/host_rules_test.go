//go:build linux

package network

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestHostRulesDeleteScript(t *testing.T) {
	t.Parallel()

	dump := `# Generated by iptables-save v1.8.9
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A PREROUTING -d 192.0.2.1/32 -i veth-1 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 5010
-A PREROUTING -d 192.0.2.1/32 -i veth-12 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 5010
-A PREROUTING -m comment --comment "kubernetes service portals" -j KUBE-SERVICES
-A POSTROUTING -s 10.11.0.1/32 -o eth0 -j MASQUERADE
-A POSTROUTING -s 10.11.0.12/32 -o eth0 -j MASQUERADE
-A POSTROUTING -s 172.17.0.0/16 ! -o docker0 -j MASQUERADE
COMMIT
`
	tokens := map[string]struct{}{"veth-1": {}, "10.11.0.1/32": {}}

	assert.Equal(t, `*nat
-D PREROUTING -d 192.0.2.1/32 -i veth-1 -p tcp -m tcp --dport 80 -j REDIRECT --to-ports 5010
-D POSTROUTING -s 10.11.0.1/32 -o eth0 -j MASQUERADE
COMMIT
`, hostRulesDeleteScript("nat", dump, tokens))

	assert.Empty(t, hostRulesDeleteScript("nat", dump, map[string]struct{}{"veth-7": {}}))
	assert.Empty(t, hostRulesDeleteScript("filter", "*filter\n:FORWARD ACCEPT [0:0]\nCOMMIT\n", tokens))
}
